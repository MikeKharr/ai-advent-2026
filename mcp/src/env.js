// Разбор окружения службы MCP на границе (ADR 2026-09-23-1227, п. 4).
// `MCP_KEY` обязателен: без него проверка входа сравнивала бы пустые строки,
// и публичный эндпоинт гонял бы наш адрес по чужим API от имени анонимов.

const NUMBERS = {
  RATE_LIMIT_PER_MIN: 10,
  RATE_LIMIT_PER_HOUR: 100,
  // Порог сигнала о переборе: столько отказов по ключу с одного адреса за
  // час — и в журнал уходит одна строка «кто-то перебирает».
  //
  // Это порог НАБЛЮДЕНИЯ, а не потолок. Потолок здесь был и снят 2026-09-24:
  // он блокировал и годный ключ с того же адреса, то есть бил ровно по тем,
  // у кого ключ есть, — у перебирающего годного ключа по определению нет.
  // Механизм не делал того, что обещало его имя (`guides/verification.md`,
  // «Механизм обязан быть тем, что описан»), и вдобавок позволял одному
  // посетителю консоли дня 16 кнопкой «проба без ключа» выключить консоль
  // для всех на час. Ключ теперь сверяется всегда; окно только считает.
  //
  // Шестьдесят: законный клиент ошибается ключом единицы раз — опечатка,
  // устаревшее значение. Шестьдесят промахов за час законной жизнью не
  // объясняются, поэтому порог — сигнал, а не шум. Нарочно не равен рабочим
  // окнам: другая величина и другой смысл.
  REFUSAL_SIGNAL_PER_HOUR: 60,
  PORT: 8083,
}

export function parseEnv(source = process.env) {
  const errors = []
  const env = {}

  const key = source.MCP_KEY ?? ''
  if (!key) errors.push('MCP_KEY не задан')
  env.MCP_KEY = key

  for (const [name, fallback] of Object.entries(NUMBERS)) {
    const raw = source[name]
    if (raw === undefined || raw === '') {
      env[name] = fallback
      continue
    }
    const value = Number(raw)
    if (!Number.isFinite(value) || value <= 0) {
      errors.push(`${name}: ожидалось положительное число, получено ${JSON.stringify(raw)}`)
      env[name] = fallback
      continue
    }
    env[name] = value
  }

  return { env, errors }
}
