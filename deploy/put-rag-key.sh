#!/usr/bin/env bash
# Кладёт deploy/rag.env с ключом RAG_KEY на сервер.
#
# ADR 2026-09-29-1639, п. 5. Ключ — вход на https://challenge.zpq.ai/rag для
# клиента Claude Code на ноутбуке владельца. Это ПЕРВЫЙ секрет проекта с
# третьим местом жизни: обычно секрет живёт в GitHub Secrets и в .env на
# сервере, здесь добавляется личная конфигурация Claude Code. Норма ADR
# 2026-09-23-1227, п. 2 («ключ не покидает сервер») нарушена сознательно —
# без этого клиент с ноутбука невозможен вовсе.
#
# Что этот ключ стоит при утечке: не деньги, а ядро общей машины — суточный
# потолок вызовов эмбеддинга. Ключей к моделям и ключа роутера у единицы rag
# нет, сеть у неё отдельная (deploy/compose.yml, сеть `rag`).
#
# Ключ вводится скрытно и уходит на сервер по ssh через stdin: он не пишется
# на диск локальной машины, не попадает в историю shell, в список процессов и
# в вывод. Скрипт не печатает его ни при каком исходе — только имена.
#
# Значение годится любое длинное случайное. Если своего нет, годится вывод
#   head -c 32 /dev/urandom | base64
# выполненный СНАЧАЛА у себя (значение попадёт в буфер обмена и в окно
# терминала, но не в файл истории и не на сервер лишний раз), а потом
# вставленный сюда.
#
# Запуск:  bash deploy/put-rag-key.sh
# Переопределения: SSH_KEY=..., SERVER=user@host
#
# После него единицу надо перезапустить — она читает окружение на старте.
# С захода 4 ключ обязателен: без него служба выходит с кодом 2 и до
# /healthz не доходит (rag/serve.py, main).
#
# ТО ЖЕ ЗНАЧЕНИЕ НУЖНО ПОЛОЖИТЬ В ОКРУЖЕНИЕ НОУТБУКА — туда, откуда его
# видит Claude Code (профиль оболочки или менеджер секретов): .mcp.json в
# корне репозитория подставляет ${RAG_KEY} из окружения процесса.
# Это условие compliance к PR #282, и оно не про удобство. Без переменной
# каждая сессия из каталога репозитория шлёт на публичный /rag строку
# шаблона как ключ; служба считает это отказом по ключу, а сигнал
# refusal_burst срабатывает на 20 отказах с адреса за час — единственный
# сигнал «перебирают» приходил бы от своего же ноутбука и перестал бы
# что-либо значить.
#
# Значение в окружение ноутбука этот скрипт не кладёт намеренно: он не
# знает, где владелец держит секреты, а писать ключ в профиль оболочки за
# него — не его дело.

set -euo pipefail

SSH_KEY="${SSH_KEY:-$HOME/.ssh/advent_deploy}"
SERVER="${SERVER:-advent@challenge.zpq.ai}"
REMOTE_PATH="ai-advent-2026/deploy/rag.env"

printf 'Вставьте RAG_KEY (ввод не отображается) и нажмите Enter:\n> '
read -rs RAG_KEY || true
printf '\n'

if [ -z "${RAG_KEY:-}" ]; then
  echo "Ключ не введён — ничего не сделано." >&2
  exit 1
fi
if [ "${#RAG_KEY}" -lt 24 ]; then
  echo "Предупреждение: ключ короче 24 знаков. Продолжаю." >&2
fi

# Скрипт выполняется на сервере, ключ приходит первой строкой stdin.
REMOTE_SCRIPT=$(cat <<REMOTE
set -eu
umask 077
f="${REMOTE_PATH}"
read -r key
if [ -f "\$f" ]; then
  tmp="\$(mktemp "\$(dirname "\$f")/.rag.XXXXXX")"
  trap 'rm -f "\$tmp"' EXIT
  # Код 1 у grep — «нет совпадений», это норма. Код 2 — настоящая ошибка,
  # и тогда падаем, а не кладём на место пустой файл.
  grep -v '^RAG_KEY=' "\$f" > "\$tmp" || [ \$? -eq 1 ]
  printf 'RAG_KEY=%s\n' "\$key" >> "\$tmp"
  mv "\$tmp" "\$f"
  echo "Обновлён RAG_KEY, остальные значения файла сохранены."
else
  { echo '# Ключ входа на /rag. Только на сервере, chmod 600.'
    echo '# Создан deploy/put-rag-key.sh (ADR 2026-09-29-1639, п. 5).'
    printf 'RAG_KEY=%s\n' "\$key"
  } > "\$f"
  echo "Файл создан."
fi
chmod 600 "\$f"
ls -l "\$f"
# Проверка именами без значений — норма проекта для env-файлов.
grep -o '^[A-Z_]*=' "\$f"
REMOTE
)

printf '%s\n' "$RAG_KEY" | ssh -i "$SSH_KEY" "$SERVER" "$REMOTE_SCRIPT"

cat <<'EOF'

Осталось сделать:
  1. Перезапустить единицу, иначе она работает со старым окружением:
       ssh <сервер> 'cd ai-advent-2026/deploy && docker compose up -d rag'
  2. Положить то же значение в личную конфигурацию Claude Code на ноутбуке —
     это делает заход 4, файл .mcp.json читает ${RAG_KEY} из окружения.
EOF
