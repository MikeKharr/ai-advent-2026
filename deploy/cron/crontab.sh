#!/bin/sh
# Сборка таблицы busybox crond из ЕДИНСТВЕННОГО источника каденции —
# `scheduleUtc` работы в `agents/config/jobs.json`.
#
#   crontab.sh <путь к jobs.json>   → таблица на stdout
#
# Почему так. Каденция лежала в двух файлах разом: строка в
# `deploy/cron/crontabs/root` исполняла, `scheduleUtc` в `jobs.json` обещал
# посетителю «следующий срок» на экране дня 18. Совпадение держала
# механическая сверка, то есть правка частоты была правкой двух файлов —
# и «настройкой» не была. Копия убрана: файл остался один, таблицу для
# crond собирает этот скрипт на старте контейнера времени. Менять частоту —
# одна строка `scheduleUtc` в `agents/config/jobs.json`.
#
# Время в таблице — UTC. Это не пожелание: суточный потолок стартов сервис
# агентов считает по суткам UTC, а busybox crond считает сроки по
# localtime(). Сдвиг пояса развёл бы сутки расписания и сутки счётчика,
# ничего при этом не сломав на вид. Пояс — условие старта (`entrypoint.sh`)
# и печатается в каждом тике (`tick.sh` печатает `date -u` и `date` рядом).
#
# Разбор строчный, а не JSON-разбором: в образе alpine нет ни jq, ни node.
# Дыра здесь была бы тихой — таблица без строки означала бы снятое
# расписание, — поэтому «работ не найдено» и любой непонятый знак это отказ
# со своим текстом, а не пустой вывод. Что строчный разбор понимает тот же
# файл, что `JSON.parse`, держит `test/cron-schedule.test.js`; что его так же
# понимает busybox awk в настоящем образе — шаг CI «Образ cron умеет crond и
# wget --post-data».
#
# -f (без раскрытия шаблонов) обязателен, а не про запас: `*` расписания
# иначе раскрылся бы в имена файлов при разборе полей ниже.
set -euf

src=${1:?crontab.sh: не указан путь к jobs.json}
[ -r "$src" ] || { echo "crontab.sh: $src не читается" >&2; exit 1; }

# Пары «id<TAB>scheduleUtc» в порядке файла. Ключи опознаются по началу
# строки, поэтому ни "agentId", ни строка промпта под них не попадают.
# Коды: 3 — scheduleUtc без id перед ним, 4 — ни одной работы.
rows=$(awk '
  function val(line) {
    sub(/^[^:]*:[ \t]*"/, "", line)
    sub(/".*$/, "", line)
    return line
  }
  /^[ \t]*"id"[ \t]*:/ { id = val($0); next }
  /^[ \t]*"scheduleUtc"[ \t]*:/ {
    if (id == "") { bad = 1; exit 3 }
    printf "%s\t%s\n", id, val($0)
    id = ""
    n++
    next
  }
  END { if (bad) exit 3; if (n == 0) exit 4 }
' "$src") || {
  code=$?
  case "$code" in
    3) echo "crontab.sh: в $src поле scheduleUtc встретилось раньше своего id" >&2 ;;
    4) echo "crontab.sh: в $src не найдено ни одной работы — расписание было бы снято молча" >&2 ;;
    *) echo "crontab.sh: разбор $src не удался (awk вернул $code)" >&2 ;;
  esac
  exit 1
}

# Значения уходят в таблицу, которую исполняет root, поэтому оба поля
# проверяются по белому списку знаков, а не по «файл же наш».
tab=$(printf '\t')
while IFS="$tab" read -r id sched; do
  case "$id" in
    [a-z]*) ;;
    *) echo "crontab.sh: имя работы «${id}» начинается не со строчной латинской буквы" >&2; exit 1 ;;
  esac
  case "$id" in
    *[!a-z0-9-]*) echo "crontab.sh: в имени работы «${id}» знак вне [a-z0-9-]" >&2; exit 1 ;;
  esac
  # shellcheck disable=SC2086 # деление на поля здесь и нужно; раскрытия нет (set -f)
  set -- $sched
  [ "$#" -eq 5 ] || { echo "crontab.sh: расписание работы «${id}» — не пять полей: «${sched}»" >&2; exit 1; }
  for field in "$@"; do
    case "$field" in
      # Дефиса в списке НЕТ намеренно, и это не про инъекцию. Диапазоны
      # (`9-17`) сборщик принял бы, а `parseSchedule` сервиса агентов их
      # отвергает — и реестр работ не загрузился бы целиком. Каденция ушла бы
      # в прод при зелёном прогоне: контейнер времени тикает, а каждый тик
      # получает 404 no_jobs и экран дня 18 срока не показывает. Белый список
      # здесь — общая грамматика двух потребителей одной строки, поэтому в
      # нём ровно то, что понимают оба: цифры, `*`, `*/N` и списки через
      # запятую (находка compliance к PR #236).
      *[!0-9*/,]*) echo "crontab.sh: в расписании работы «${id}» знак вне [0-9*/,]: «${field}» — сервис агентов понимает только цифры, «*», «*/N» и списки через запятую" >&2; exit 1 ;;
    esac
  done
  # Три последних поля — только `*`, как и у parseSchedule. Строка вида
  # `0 6 1 * *` иначе ушла бы в таблицу (знаки законные, полей пять), crond
  # тикал бы раз в месяц, а реестр работ не загрузился бы вовсе.
  #
  # ГРАНИЦА, названная прямо. Диапазоны чисел здесь НЕ проверяются:
  # `0 99 * * *` и `0 */30 * * *` этот скрипт примет, хотя parseSchedule
  # отвергнет оба. Повторять здесь арифметику диапазонов значило бы завести
  # второй разборщик грамматики — ровно то, из-за чего этот PR и начался.
  # Грамматика одна и живёт в `agents/src/jobs/schedule.js`; что настоящий
  # `jobs.json` через неё проходит, держит `test/cron-schedule.test.js`
  # настоящим `loadJobs`, и негодная каденция не доживает до мержа.
  case "$3$4$5" in
    '***') ;;
    *) echo "crontab.sh: у работы «${id}» день месяца, месяц или день недели не «*»: «${sched}» — сервис агентов поддерживает в этих полях только «*»" >&2; exit 1 ;;
  esac

  printf '%s /cron/tick.sh %s\n' "$sched" "$id"
done <<EOF
$rows
EOF
