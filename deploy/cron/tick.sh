#!/bin/sh
# Один тик: постучаться в ручку запуска работы и напечатать ответ в журнал
# контейнера. Ни состояния, ни разбора ответа, ни повторов: отказ — это отказ
# одного срока, следующий придёт по расписанию. Догона нет.
#
#   tick.sh <имя работы>
set -eu

job=${1:?tick.sh: не указано имя работы}

# Вывод — в стандартный вывод процесса 1, а не в свой: busybox crond
# перехватывает stdout задания и пытается отдать его sendmail, которого в
# образе нет (проверено по miscutils/crond.c, ADR «Проверено лично»).
# Поэтому всё пишется сюда, а на собственный stdout не уходит ничего.
out=/proc/1/fd/1

# `date -u` и `date` рядом — чтобы сдвиг пояса было видно в
# `docker compose logs cron`, а не выводить его из того, что запуски пришли
# не тогда. Старт контейнера сдвиг уже не пропустил бы (entrypoint.sh), эта
# строка — свидетельство в журнале для каждого тика.
utc=$(date -u +%Y-%m-%dT%H:%M:%SZ)
local=$(date +%Y-%m-%dT%H:%M:%S%z)

# --timeout 20: тик не должен висеть до следующего срока. Ручка отвечает
# сразу решением («запуск создан» / «занято» / «потолок»), а не концом работы,
# — ждать здесь нечего.
# Тело `{}`, а не пустое: так тик не зависит от того, принимает ли busybox
# wget пустое --post-data.
if answer=$(wget -q -O - --timeout=20 --tries=1 \
      --header="Authorization: Bearer $(cat /run/agent.key)" \
      --header="Content-Type: application/json" \
      --post-data='{}' \
      "http://agents:8082/v1/jobs/${job}/trigger" 2>&1); then
  printf '{"event":"tick","job":"%s","utc":"%s","local":"%s","answer":%s}\n' \
    "$job" "$utc" "$local" "$answer" > "$out"
else
  # Тело ответа сюда не печатается: при отказе wget отдаёт в него свою
  # диагностику, а не JSON ручки, и подставлять её в поле answer как JSON
  # значило бы писать битые строки в журнал.
  printf '{"event":"tick_failed","job":"%s","utc":"%s","local":"%s"}\n' \
    "$job" "$utc" "$local" > "$out"
fi
