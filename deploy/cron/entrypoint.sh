#!/bin/sh
# Точка входа cron-контейнера планировщика (ADR 2026-09-28-0736, п. 6).
#
# Контейнер решает ТОЛЬКО «когда». Решение «запускать ли сейчас» — включена ли
# работа, не идёт ли предыдущий запуск, не занят ли этот час, не исчерпан ли
# суточный потолок, есть ли ключ приложения `scheduler`, — принимает сервис
# агентов. Состояния, повторов и догона пропущенного здесь нет.
set -eu

# 1. Ключ — в файл, не в окружение задания. busybox crond ставит заданию
#    только LOGNAME, USER, HOME, SHELL и PATH: окружение контейнера оно не
#    наследует (проверено по miscutils/crond.c, ADR «Проверено лично»).
#    Поэтому tick.sh читает ключ отсюда.
if [ -z "${AGENT_KEY:-}" ]; then
  echo "cron: AGENT_KEY не задан (нет deploy/cron.env) — тик не с чем делать, старт отменён" >&2
  exit 78
fi
umask 077
printf '%s' "$AGENT_KEY" > /run/agent.key
mkdir -p /run/crontabs

# 2. Часовой пояс — условие старта, а не обещание в комментарии.
#    busybox crond считает сроки по localtime(). Суточный потолок стартов
#    сервис агентов считает по суткам UTC. Если локальное время контейнера
#    не UTC, расписание отработает те же строки по другому поясу: сутки
#    расписания разойдутся с сутками счётчика, а на вид не сломается ничего —
#    контейнер жив, запуски идут. Тихая поломка ровно того класса, ради
#    которого эта проверка и стоит здесь: при сдвиге процесс не поднимается,
#    и контейнер уходит в перезапуск на виду.
#
#    В образе alpine нет tzdata, и TZ не задан, поэтому в норме здесь +0000.
#    Проверка стоит не потому, что пояс подозрителен сегодня, а потому, что
#    его молча меняет любой будущий `TZ=` в compose или tzdata в образе.
offset=$(date +%z)
if [ "$offset" != "+0000" ]; then
  echo "cron: локальное время контейнера не UTC (смещение $offset), а суточный потолок стартов считается по суткам UTC — старт отменён" >&2
  exit 78
fi

echo "cron: смещение времени $offset, ключ принят" >&2

# 3. Таблица crond собирается из единственного источника каденции —
#    `scheduleUtc` работы в `agents/config/jobs.json`, примонтированном сюда
#    на чтение (`/jobs.json`). Второй копии расписания в репозитории нет:
#    тот же файл читает сервис агентов, когда обещает экрану дня 18
#    «следующий срок», и разойтись двум потребителям больше не с чем.
#
#    Отказ сборки — выход, а не пустая таблица: контейнер без строк выглядел
#    бы работающим планировщиком, у которого просто не настал срок.
if ! /cron/crontab.sh /jobs.json > /run/crontabs/root; then
  echo "cron: таблица crond не собралась из /jobs.json (сообщение выше) — старт отменён" >&2
  exit 78
fi

# Строки печатаются в журнал целиком: по `docker compose logs cron` видно,
# по какому расписанию контейнер работает на самом деле, а не по какому он
# должен был бы. Это же читает шаг CI, сверяя таблицу с jobs.json.
# Порядок строк — предмет проверки, а не оформление: сначала таблица,
# и только потом отметка о приёме. Шаг CI ждёт именно отметку, поэтому к
# моменту, когда он начинает читать таблицу из журнала, она там уже есть.
echo "cron: расписание из jobs.json:" >&2
while IFS= read -r line; do echo "cron:   $line" >&2; done < /run/crontabs/root
echo "cron: расписание принято, запуск crond" >&2

# -c: каталог таблиц — /run/crontabs на tmpfs, куда пишет этот скрипт.
# Таблица собирается на старте, поэтому новая каденция доезжает пересозданием
# контейнера времени — его делает шаг выкатки после `docker compose up -d`.
exec crond -f -l 8 -c /run/crontabs
