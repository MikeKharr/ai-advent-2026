// Реестр провайдеров — шов (ADR 2026-09-08-1748, п. 2). Роутер зависит от
// интерфейса `list()`, а не от способа наполнения. Сейчас — статическая
// конфигурация; за тем же интерфейсом позже встанут хартбиты или service
// discovery. Реестр отвечает только за существование и описание;
// здоровье всегда считает роутер.

export function createStaticRegistry(providers) {
  const snapshot = providers.map((p) => ({ ...p, revision: p.revision ?? 1 }))
  return {
    /** Синхронный снимок: на пути запроса ввода-вывода нет. */
    list() {
      return snapshot
    },
  }
}
