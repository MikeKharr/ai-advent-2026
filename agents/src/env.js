// Разбор окружения сервиса агентов на границе. Ключ сервиса и ключ
// приложения у роутера обязательны: без первого проверка авторизации
// сравнивала бы пустые строки, без второго роутер отвечал бы 401 на всё.

const NUMBERS = {
  // Потолок пользовательского max_tokens. Поднят до 4096 под умолчание дня 8
  // в 3000: умолчание, совпадающее с пределом, не оставляет запаса.
  MAX_OUTPUT_TOKENS: 4096,
  WINDOW_SIZE: 1000, // сколько статей держим в окне архива
  REFRESH_MIN_MINUTES: 15, // не чаще, чем раз в столько минут, опрашиваем ленты
  MAX_AGE_DAYS: 180, // дольше этого чужие тексты в архиве не хранятся
  // Ноутбук отвечает минутами: двадцать секунд на загрузку модели плюс
  // около восьми токенов в секунду. Облачные модели в этот потолок
  // укладываются с огромным запасом.
  ROUTER_TIMEOUT_MS: 240_000,
  RUN_TTL_MINUTES: 10, // готовый запуск живёт в памяти столько
  // Диалог без активности живёт столько часов, потом удаляется целиком
  // (решение владельца 2026-09-12, ADR 2026-09-09-1906).
  SESSION_TTL_HOURS: 30,
  // Профиль дня 11 живёт дольше своих диалогов: настройки, правила и темы
  // переживают переписку (решение владельца 7, ADR 2026-09-15-2024).
  PROFILE_TTL_DAYS: 30,
  // Потолок живых профилей (решение владельца 8): шестой не создаётся.
  PROFILE_CAP: 5,
  // Живых диалогов на профиль — временное рабочее значение той же записи.
  PROFILE_SESSION_CAP: 20,
  // Запуск дня 13 на паузе дольше этого отменяется: замок сессии снимается,
  // и диалог не остаётся запертым навсегда (ADR 2026-09-21-1747, п. 3).
  PAUSE_TTL_MINUTES: 60,
  PORT: 8082,
}

export function parseEnv(source = process.env) {
  const errors = []
  /** Замечания, которые не валят старт, но обязаны попасть в журнал. */
  const notes = []
  const env = {
    ROUTER_URL: source.ROUTER_URL || 'http://router:8081',
    STORE_FILE: source.STORE_FILE || '/data/store.json',
    SESSIONS_FILE: source.SESSIONS_FILE || '/data/sessions.db',
    // Журнал этапов дня 13 — на том же томе, что и диалоги
    // (ADR 2026-09-21-1747, п. 7).
    STAGE_LOG_FILE: source.STAGE_LOG_FILE || '/data/stage-log.csv',
    // Запуски планировщика дня 18 — свой файл на том же томе: миграции и
    // 30-часовая уборка диалогов сводок не касаются (ADR 2026-09-28-0736, п. 6).
    JOBS_FILE: source.JOBS_FILE || '/data/jobs.db',
    // Ключ приложения `scheduler` у роутера. `null` — планировщик выключен
    // по устройству: расход по таймеру без него невозможен. Поэтому он НЕ в
    // списке обязательных ключей ниже: сервис агентов обязан подниматься и
    // без планировщика. Именно `null`, а не пустая строка: пустая строка
    // среди значений окружения означала бы «задан и пуст».
    ROUTER_APP_KEY_SCHEDULER: source.ROUTER_APP_KEY_SCHEDULER || null,
  }

  for (const name of ['AGENT_KEY', 'ROUTER_APP_KEY']) {
    const value = source[name] ?? ''
    if (!value) errors.push(`${name} не задан`)
    env[name] = value
  }

  // Ключ планировщика, СОВПАВШИЙ с ключом приложения `agents`, — не ключ
  // планировщика, а его копия: роутер узнал бы по нему приложение `agents`,
  // ночная работа тратила бы $10 бюджета дней 6–16 и в журнале была бы от них
  // неотличима. Отдельный потолок $0,5 при этом исчезает МОЛЧА — ничего не
  // ломается, и заметить нечем.
  //
  // Строки `deploy/.env.example` владелец переносит в `agents.env` руками
  // (правило A8 ADR 2026-09-24-1230: секрет вводится, а не коммитится), и
  // перенос не той строки — ровно один промах мыши. Здесь он становится
  // громким: ключ считается НЕЗАДАННЫМ, планировщик падает на второй уровень
  // выключения (ручка отвечает 503, модель не вызывается), а `/healthz`
  // говорит «нет».
  //
  // Почему не `errors`: опечатка в ключе ПЛАНИРОВЩИКА не должна ронять
  // сервис, в котором живут дни 6–16. Отказывает то, что настроено неверно,
  // и только оно (находка `compliance` Б4, PR #237).
  if (env.ROUTER_APP_KEY_SCHEDULER && env.ROUTER_APP_KEY_SCHEDULER === env.ROUTER_APP_KEY) {
    env.ROUTER_APP_KEY_SCHEDULER = null
    notes.push({
      event: 'scheduler_key_same_as_app',
      message:
        'ROUTER_APP_KEY_SCHEDULER совпадает с ROUTER_APP_KEY: это копия ключа приложения agents, ' +
        'а не ключ приложения scheduler. Планировщик выключен — отдельного потолка расхода у него не было бы.',
    })
  }

  for (const [name, fallback] of Object.entries(NUMBERS)) {
    const raw = source[name]
    if (raw === undefined || raw === '') {
      env[name] = fallback
      continue
    }
    const value = Number(raw)
    if (!Number.isFinite(value) || value <= 0) {
      errors.push(`${name}: ожидалось положительное число, получено ${JSON.stringify(raw)}`)
      env[name] = fallback
      continue
    }
    env[name] = value
  }

  return { env, errors, notes }
}
