// Промпты профиля — шов дня 15 (ADR 2026-09-23-0646, п. 2).
//
// Машина состояний берёт текст каждого промпта через этот объект и ни в
// одном месте не спрашивает «а это день 15?». ADR 2026-09-22-0827, п. 1,
// назвал третий флаг пределом: день 14 прошёл объектом `invariants`, день 15
// проходит объектом `prompts` — и умолчание `registryPrompts` возвращает
// пустую карту, то есть «все промпты из реестра», без единой ветки у места
// вызова.
//
// Пустая карта — не «нет промптов», а «ничего не переписано»: тексты
// умолчаний живут там же, где жили, — в реестре, `llm.js` и `invariants.js`.
// Копии умолчаний в хранилище нет намеренно (см. `sessions.promptsOf`).

import { PROFILE_PROMPT_IDS } from './params.js'

const EMPTY = new Map()

/**
 * Умолчание для агентов дней 13 и 14: промпты только из реестра и констант.
 *
 * `ownsSystem: false` — системный промпт ответа этому агенту можно прислать
 * со входом запуска (`system`), как было с дня 6.
 */
export const registryPrompts = {
  ownsSystem: false,
  resolve: () => EMPTY,
}

/**
 * Промпты профиля дня 15: пять текстов из таблицы `profile_prompts`.
 *
 * `ownsSystem: true` — промпт ответа принадлежит профилю, и поле `system` во
 * входе запуска отвергается (ADR, п. 2): иначе прямой `POST` подменял бы
 * системный промпт мимо профиля, и окно «Об агенте» показывало бы не тот
 * текст, которым на деле отвечает агент.
 */
export function createProfilePrompts({ sessions }) {
  return {
    ownsSystem: true,
    /** Карта promptId → текст. Чего нет в карте, то берётся из умолчания. */
    resolve: (profileId) => sessions.promptsOf(profileId),
  }
}

/** Пять идентификаторов промптов профиля — для ручек сервиса и страницы. */
export { PROFILE_PROMPT_IDS }
