// Дефект владельца 2026-09-22: пауза, закрытое окно, «Продолжить» в другом
// окне — «визуально ничего не поменялось», а позже «запрос уже отработал».
//
// Серверная половина причины проверена поведенчески против НАСТОЯЩЕГО сервиса
// (`agents/test/day13-reconnect.test.js`): ручка паузы возобновляла запуск и
// тогда, но отвечала 409 на уже завершившийся. Вторая половина — на странице:
// подписка на поток событий открывалась ТОЛЬКО в обработчике отправки, и
// вкладка, не отправлявшая сообщения, не видела ни «Продолжаю», ни этапов, ни
// конца запуска.
//
// Проверки здесь структурные, и это названо прямо: в дне нет DOM-окружения для
// тестов, поэтому проверяется исходный текст страницы — подписка заведена в
// одном месте и её зовёт подхват запуска. Живой прогон в браузере они не
// заменяют.

import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { test } from 'node:test'

const here = dirname(fileURLToPath(import.meta.url))
const page = readFileSync(join(here, '..', 'public', 'index.html'), 'utf8')

test('подписка на поток событий одна на всю страницу', () => {
  const opened = page.match(/new EventSource\(/g) ?? []
  assert.equal(
    opened.length,
    1,
    'вторая подписка означала бы, что подхват запуска слушает поток по-своему',
  )
  assert.match(
    page,
    /const followRun = \(runId, run, answered\) => \{/,
    'подписка обязана жить в отдельной функции: её зовут два разных места',
  )
})

test('вкладка не подписывается дважды на один запуск', () => {
  assert.match(
    page,
    /if \(following\?\.runId === runId\) return;/,
    'без этого повторное чтение переписки открывало бы поток за потоком',
  )
})

test('подхваченный у сервиса запуск подписывается на поток', () => {
  // Это и есть исправленный дефект: без подписки «Продолжить» снимает паузу у
  // сервиса, а на экране не меняется ничего до самого конца.
  assert.match(
    page,
    /if \(following\?\.runId !== run\.id\) \{[\s\S]{0,600}?followRun\(run\.id, local,/,
    'adoptRun обязан подписывать вкладку на живой запуск, а не только рисовать полосу',
  )
})

test('отправка сообщения пользуется той же подпиской', () => {
  assert.match(page, /followRun\(runId, run, answered\);/)
})

test('«Продолжить» по завершившемуся запуску объясняет состояние, а не показывает отказ', () => {
  assert.match(
    page,
    /if \(result\?\.finished\) \{/,
    'ответ ручки о завершившемся запуске обязан быть обработан как состояние',
  )
  assert.equal(
    /'Запуск уже завершён'/.test(page),
    false,
    'прежний отказ по коду 409 не должен вернуться: требование владельца — не отказывать на действие',
  )
  assert.match(
    page,
    /if \(result\?\.finished\) \{[\s\S]{0,500}?syncChat\(\)/,
    'после объяснения страница обязана показать, чем запуск кончился',
  )
})
