// Разбор окружения дня 24 на границе. Ключей к моделям и к роутеру у дня нет,
// ключа к службе поиска — тоже: день ходит ТОЛЬКО к сервису агентов
// (ADR 2026-09-09-0854) и предъявляет ему AGENT_KEY. В `rag` по MCP ходит сам
// сервис агентов под своим RAG_KEY (ADR 2026-10-04-0735, п. 1) — у дня этого
// ключа нет вовсе, и поэтому его нельзя потерять здесь.
//
// Ключ живёт в этом процессе; страница его не знает, не получает и не
// показывает (I-1).
//
// Числа окон и суточный потолок — КОПИЯ дня 22 (ADR 2026-10-05-0544, п. 4):
// запуск зовёт платную модель, поэтому суточный потолок охраняет деньги, а не
// чужие API.
//
// Чего здесь НЕТ в отличие от дня 20, и это не упущение: cookie, сессий и
// срока их жизни. Задание дня — один вопрос, переписки у дня нет
// (ADR 2026-10-04-0735, п. 1, унаследовано днём 24),
// поэтому нет и COOKIE_PATH, COOKIE_SECURE, SESSION_TTL_HOURS. Окна записей
// тоже нет: ручки, которая правила бы общую базу сервиса, у дня нет.

/**
 * Режимы отбора, которые принимает `cited-agent`
 * (`agent_docs/guides/day24-cited-contract.md`, «Вход»). Их ДВА, а не три:
 * режим `rag` дня 23 — это «до» его сравнения, а день 24 строится на отборе.
 *
 * Умолчания у режима нет ни у агента, ни на странице: запуск без названного
 * режима означал бы отбор неизвестно какой. Называет его СЕРВЕР ДНЯ, а не
 * посетитель, — выбора режима на экране нет (ADR 2026-10-05-0544, п. 2.4:
 * «Режим один», и какой именно, задаёт правило по числам дня 23).
 */
export const MODES = ['rerank', 'rewrite']

/**
 * Какой из двух режимов работает на этой странице.
 *
 * Правило ADR (п. 2.4): `rewrite`, если MRR@10 после отбора выше `rerank` не
 * меньше чем на 0,02, иначе `rerank`. ЧИСЛА ДНЯ 23 НА МОМЕНТ ЭТОЙ ЕДИНИЦЫ
 * ЕЩЁ НЕТ — прогон дня 23 идёт параллельно, — поэтому в коде стоит дешёвый
 * `rerank`, а переменная даёт возможность поставить `rewrite` файлом
 * `deploy/day24.env`, когда число появится, без правки образа.
 *
 * Литерала режима на странице нет нигде: он приходит в ответе запуска, и
 * вписанный в разметку разошёлся бы с сервером молча — тот же довод, что у
 * суточного предела.
 */
const DEFAULT_MODE = 'rerank'

const NUMBERS = {
  RATE_LIMIT_PER_MIN: 5,
  RATE_LIMIT_PER_HOUR: 30,
  // Окно чтений (ADR 2026-09-29-1600, п. 2): поток событий запуска. Число то
  // же, что у дня 20, и так же взято ПО АНАЛОГИИ со службой MCP, замером не
  // подтверждено. Умолчание живёт в коде — в deploy/day24.env переменной нет.
  RATE_LIMIT_READS_PER_HOUR: 600,
  // Запуск зовёт модель через роутер — здесь потолок охраняет деньги. В дне 24
  // вызовов на запуск два-три: отбор (реранкер), переписывание в режиме
  // `rewrite` и ответ со схемой; при пустом отборе ответ тоже вызов, только
  // дешевле — без блока фрагментов (ADR 2026-10-05-0544, п. 4). Потолок
  // считает запуски, а не вызовы, поэтому верхняя оценка дня —
  // 50 × $0,013 ≈ $0,65 при потолке $10 приложения. Он же держит суточный
  // потолок эмбеддера службы `rag`: 50 запусков дня — не больше 100
  // эмбеддингов из её 500 за сутки.
  MAX_DAILY_CALLS: 50,
  // Быстрые вызовы к сервису агентов. Поток событий идёт без таймаута, пока
  // агент его не закроет.
  AGENT_TIMEOUT_MS: 10_000,
  PORT: 8080,
}

export function parseEnv(source = process.env) {
  const errors = []
  const env = {
    AGENT_URL: source.AGENT_URL || 'http://agents:8082',
    AGENT_ID: source.AGENT_ID || 'cited-agent',
  }

  // Режим проверяется по списку, а не берётся как пришёл: чужое значение
  // уехало бы в сервис и вернулось оттуда отказом, уже заняв слот окна.
  const mode = source.RUN_MODE ?? ''
  if (mode === '') env.RUN_MODE = DEFAULT_MODE
  else if (MODES.includes(mode)) env.RUN_MODE = mode
  else {
    errors.push(`RUN_MODE: ожидалось ${MODES.join(' или ')}, получено ${JSON.stringify(mode)}`)
    env.RUN_MODE = DEFAULT_MODE
  }

  const key = source.AGENT_KEY ?? ''
  if (!key) errors.push('AGENT_KEY не задан')
  env.AGENT_KEY = key

  // Ключ оператора (ADR 2026-10-05-1130). Пустой или отсутствующий — это НЕ
  // ошибка конфигурации, а выключенная возможность: совпадений не бывает ни с
  // каким заголовком, включая пустой, и день работает как до того ADR.
  // Умолчания у него нет и быть не может — умолчание означало бы общеизвестный
  // ключ, то есть снятые окна у всех.
  env.EVAL_KEY = source.EVAL_KEY ?? ''

  for (const [name, fallback] of Object.entries(NUMBERS)) {
    const raw = source[name]
    if (raw === undefined || raw === '') {
      env[name] = fallback
      continue
    }
    const value = Number(raw)
    if (!Number.isFinite(value) || value <= 0) {
      errors.push(`${name}: ожидалось положительное число, получено ${JSON.stringify(raw)}`)
      env[name] = fallback
      continue
    }
    env[name] = value
  }

  return { env, errors }
}
