// УМОЛЧАНИЕ СУТОЧНОГО ПОТОЛКА ДНЯ 23 — под тестом, а не только в комментарии.
//
// Зачем файл появился. До него `parseEnv` дня не исполнялся ни одним тестом:
// тесты лимитера подставляют свои числа (`MAX_DAILY_CALLS: 3`, `1000`), и
// умолчание из `env.js` не проверял никто. Поэтому правка числа потолка —
// строки, которая и есть защита расхода, — оставляла прогон зелёным. На
// подъёме потолка с 50 до 150 (решение владельца 2026-10-05, ADR
// 2026-10-05-1004) это перестало быть терпимым: число стало втрое больше, а
// держателя у него не было (I-14).
//
// Что держит этот файл: ровно то, сколько запусков день разрешает за сутки по
// умолчанию, и то, что умолчание — именно умолчание, а не жёсткое число
// (переменная окружения его перебивает). Чего не держит: что 150 — верное
// число. Это решение владельца, и менять его вправе новый ADR, а не правка
// файла.
//
// Почему умолчание вообще решает: в `deploy/day23.env` на сервере лежит ТОЛЬКО
// `AGENT_KEY` (deploy/.env.example, раздел про day23.env), а `secrets.env` в
// день не подключён вовсе (deploy/compose.yml, служба `day23`: `env_file` —
// один `./day23.env`). Значит в проде работает число из этого кода, и правка
// умолчания — правка прода.

import assert from 'node:assert/strict'
import test from 'node:test'
import { parseEnv } from '../env.js'

test('умолчание суточного потолка — 150 запусков', () => {
  const { env, errors } = parseEnv({ AGENT_KEY: 'k' })
  assert.deepEqual(errors, [])
  assert.equal(env.MAX_DAILY_CALLS, 150)
})

test('окна на адрес остались прежними: подъём суточного потолка их не трогал', () => {
  // Улика различает гипотезы: если бы правка потолка задела окна, этот тест
  // покраснел бы отдельно от предыдущего. Числа — копия дня 22 (ADR
  // 2026-10-05-0544, п. 4), и решение владельца 2026-10-05 их не меняло.
  const { env } = parseEnv({ AGENT_KEY: 'k' })
  assert.equal(env.RATE_LIMIT_PER_MIN, 5)
  assert.equal(env.RATE_LIMIT_PER_HOUR, 30)
  assert.equal(env.RATE_LIMIT_READS_PER_HOUR, 600)
})

test('суточный потолок — умолчание, а не жёсткое число: окружение его перебивает', () => {
  const { env, errors } = parseEnv({ AGENT_KEY: 'k', MAX_DAILY_CALLS: '7' })
  assert.deepEqual(errors, [])
  assert.equal(env.MAX_DAILY_CALLS, 7)
})

test('негодный потолок — ошибка конфигурации, а не молчаливый откат к умолчанию', () => {
  // Молчаливый откат здесь опаснее отказа: администратор, опечатавшийся в
  // числе, получил бы потолок, которого не задавал, и узнал бы об этом по
  // расходу. `/healthz` при непустых errors отдаёт 503.
  const { errors } = parseEnv({ AGENT_KEY: 'k', MAX_DAILY_CALLS: 'много' })
  assert.equal(errors.length, 1)
  assert.match(errors[0], /MAX_DAILY_CALLS/)
})
