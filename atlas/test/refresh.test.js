import assert from 'node:assert/strict'
import { test } from 'node:test'
import { redraws } from '../web/app.js'

// Перерисовка до загрузки схемы. `resize` (на телефоне — при устоявшемся
// окне сразу после загрузки страницы), смена адреса, «Карта», глубина и
// «Весь граф» зовут перерисовку в любой момент, в том числе пока graph.json
// ещё едет. Рисовать тогда нечего, и такой вызов не должен ни падать, ни
// трогать `#canvas-msg` и `#live`: иначе посетитель на миг видит, а
// скринридер читает внутреннюю ошибку вместо настоящей причины.

test('пока схема грузится, перерисовка не выполняется: графа ещё нет', () => {
  assert.equal(redraws('loading'), false)
})

test('после отказа перерисовка не выполняется: картинка не встаёт поверх причины', () => {
  assert.equal(redraws('error'), false)
})

test('загруженная схема перерисовывается', () => {
  assert.equal(redraws('ready'), true)
})
